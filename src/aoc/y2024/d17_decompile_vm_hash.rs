// Puzzle description: https://adventofcode.com/2024/day/17

#[derive(Debug, Clone)]
struct Computer {
    a: u64,
    b: u64,
    c: u64,
    ptr: usize,
    stack: Vec<u64>,
    output: Vec<u64>,
}

impl Computer {
    fn parse(input: &str) -> Computer {
        fn read_end_nb(line: &str) -> u64 {
            line.rsplit_once(' ').unwrap().1.parse().unwrap()
        }
        fn read_end_nbs(line: &str) -> Vec<u64> {
            let csvs = line.rsplit_once(' ').unwrap().1;
            csvs.split(',').map(|s| s.parse().unwrap()).collect()
        }
        let mut lines = input.lines();
        let a = read_end_nb(lines.next().unwrap());
        let b = read_end_nb(lines.next().unwrap());
        let c = read_end_nb(lines.next().unwrap());
        lines.next(); // Skip empty line
        let stack = read_end_nbs(lines.next().unwrap());
        Computer {
            a,
            b,
            c,
            ptr: 0,
            stack,
            output: Vec::new(),
        }
    }
    fn combo(&self) -> u64 {
        let op = self.stack[self.ptr + 1];
        match op {
            x if (0..=3).contains(&x) => x,
            4 => self.a,
            5 => self.b,
            6 => self.c,
            _ => panic!("tried to eval invalid combo opcode"),
        }
    }
    fn literal(&self) -> u64 {
        self.stack[self.ptr + 1]
    }
    fn tick(&mut self) -> bool {
        if let Some(opcode) = self.stack.get(self.ptr) {
            match opcode {
                // adv
                0 => {
                    self.a >>= self.combo();
                    self.ptr += 2;
                }
                // bxl
                1 => {
                    self.b ^= self.literal();
                    self.ptr += 2;
                }
                // bst
                2 => {
                    self.b = self.combo() % 8;
                    self.ptr += 2;
                }
                // jnz
                3 => {
                    if self.a == 0 {
                        self.ptr += 2;
                    } else {
                        self.ptr = self.literal().try_into().unwrap();
                    }
                }
                // bxc
                4 => {
                    self.b ^= self.c;
                    self.ptr += 2;
                }
                // out
                5 => {
                    self.output.push(self.combo() % 8);
                    self.ptr += 2;
                }
                // bdv
                6 => {
                    self.b = self.a >> self.combo();
                    self.ptr += 2;
                }
                // cdv
                7 => {
                    self.c = self.a >> self.combo();
                    self.ptr += 2;
                }
                _ => {
                    panic!("invalid opcode encountered");
                }
            };
            true
        } else {
            false
        }
    }
}

