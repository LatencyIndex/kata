// Output i generated by the given initial a register.
fn get_output(a: u64, i: usize) -> u64 {
    let a = a >> (3 * i);
    let b = a % 8;
    let b = b ^ 5;
    let c = a >> b;
    let b = b ^ c;
    let b = b ^ 6;
    b % 8
}

// Smallest register a value, that differs from the given suffix only in bits [3i, 3i+2],
// that yields the given i-th output value.
// The bit limitation is so that it does not alter output i+1.
fn find_next_a(suffix: u64, i: usize, output: u64) -> impl Iterator<Item = u64> {
    // Output i depends on bits [3i, 3i+9]
    // Output i+1 depends on [3i+3, 3i+12]
    // To not alter output i+1, we only modify bits [3i, 3i+2]
    let max_prefix = 1 << (3 * i + 3);
    let step = 1 << (3 * i);
    (0..max_prefix)
        .step_by(step)
        .map(move |prefix| suffix + prefix)
        .filter(move |&a| get_output(a, i) == output)
}

// The lowest initial register a value that yields the given output.
fn find_a(suffix: u64, output: &[u64]) -> Option<u64> {
    let n = output.len();
    if n == 0 {
        Some(suffix)
    } else {
        // Search from the end, because that corresponds to the
        // most significant bits of a, which we want to be lowest,
        // and not have to pick higher bits because a preceding
        // solution excluded the lower ones.
        let i = n - 1;
        let x = output[i];
        find_next_a(suffix, i, x)
            .filter_map(|suffix| find_a(suffix, &output[..i]))
            .next()
    }
}

const INPUT: &str = "data/y2024/d17/input";

pub fn part1() -> String {
    let input = std::fs::read_to_string(INPUT).unwrap();
    let mut c = Computer::parse(&input);
    while c.tick() {}
    let s: Vec<String> = c.output.iter().map(|x| x.to_string()).collect();
    s.join(",")
}

pub fn part2() -> u64 {
    let input = std::fs::read_to_string(INPUT).unwrap();
    let c = Computer::parse(&input);
    find_a(0, &c.stack).unwrap()
}

